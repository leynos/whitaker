//! Rendering and emission of the localized complexity diagnostic.
//!
//! Resolution goes through the shared Fluent loader so translations and the
//! fallback path stay consistent with the other Whitaker lints. The fallback
//! text is English and locale-invariant because this message has no
//! locale-dependent inflection.

use std::borrow::Cow;

use rustc_lint::{LateContext, LintContext};
use rustc_span::Span;
use whitaker_common::{
    Arguments,
    Localizer,
    MessageResolution,
    i18n::{DiagnosticMessageSet, FluentValue},
    noop_reporter,
    safe_resolve_message_set,
};

use super::{LINT_NAME, MACRO_AWARE_COGNITIVE_COMPLEXITY, MESSAGE_KEY};

/// Everything one emission needs to render and place the diagnostic.
pub(super) struct Report<'a> {
    /// The span the diagnostic underlines.
    pub(super) span: Span,
    /// The identifier text or closure placeholder named by the message.
    pub(super) subject: &'a str,
    /// The reported complexity total.
    pub(super) score: u64,
    /// The configured limit that the total exceeded.
    pub(super) limit: u64,
}

/// Resolve the primary, note, and help text for one diagnostic.
pub(super) fn render(
    localizer: &Localizer,
    subject: &str,
    score: u64,
    limit: u64,
) -> DiagnosticMessageSet {
    let args = diagnostic_arguments(subject, score, limit);
    let resolution = MessageResolution {
        lint_name: LINT_NAME,
        key: MESSAGE_KEY,
        args: &args,
    };

    safe_resolve_message_set(localizer, resolution, noop_reporter, || {
        fallback_messages(subject, score, limit)
    })
}

/// Emit one complexity diagnostic for `report`.
pub(super) fn emit(cx: &LateContext<'_>, report: &Report<'_>, localizer: &Localizer) {
    let anchor = report.span;
    let messages = render(localizer, report.subject, report.score, report.limit);
    let primary = messages.primary().to_owned();
    let note = messages.note().to_owned();
    let help = messages.help().to_owned();

    cx.emit_span_lint(
        MACRO_AWARE_COGNITIVE_COMPLEXITY,
        anchor,
        rustc_lint::errors::DiagDecorator(move |lint| {
            lint.primary_message(primary);
            lint.span_note(anchor, note);
            lint.help(help);
        }),
    );
}

/// Build the Fluent arguments consumed by the message bundle.
fn diagnostic_arguments(subject: &str, score: u64, limit: u64) -> Arguments<'static> {
    let mut args: Arguments<'static> = Arguments::default();
    args.insert(
        Cow::Borrowed("name"),
        FluentValue::String(Cow::Owned(subject.to_owned())),
    );
    args.insert(
        Cow::Borrowed("score"),
        FluentValue::from(fluent_integer(score)),
    );
    args.insert(
        Cow::Borrowed("limit"),
        FluentValue::from(fluent_integer(limit)),
    );
    args
}

/// Clamp an unsigned count into Fluent's signed 64-bit range.
fn fluent_integer(value: u64) -> i64 { i64::try_from(value).unwrap_or(i64::MAX) }

/// Build the built-in English messages used when a translation is missing.
fn fallback_messages(subject: &str, score: u64, limit: u64) -> DiagnosticMessageSet {
    DiagnosticMessageSet::new(
        format!("`{subject}` has a cognitive complexity of {score} (limit {limit})."),
        String::from("Branching generated by macro expansion is not counted."),
        String::from("Split the function into smaller functions with clear names."),
    )
}
