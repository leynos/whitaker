//! Value types shared by continuation scanning, classification, and rewriting.

/// Source bytes inside a cooked string literal, with the quotes excluded.
///
/// All offsets produced by the domain crate are relative to this body. The
/// compiler adapter is responsible for translating them to token offsets.
///
/// # Examples
///
/// ```
/// use whitaker_string_literals::facts::LiteralBody;
///
/// let body = LiteralBody::new("alpha \\\nbeta");
/// assert_eq!(body.as_str(), "alpha \\\nbeta");
/// assert_eq!(body.len(), 12);
/// ```
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct LiteralBody<'a>(&'a str);

impl<'a> LiteralBody<'a> {
    /// Wraps the source body of a cooked string literal.
    ///
    /// The caller must pass only the bytes between the literal's quotes.
    ///
    /// # Examples
    ///
    /// ```
    /// use whitaker_string_literals::facts::LiteralBody;
    ///
    /// let body = LiteralBody::new("alpha");
    /// assert_eq!(body.as_str(), "alpha");
    /// ```
    #[must_use]
    pub const fn new(source: &'a str) -> Self { Self(source) }

    /// Returns the original body source.
    ///
    /// # Examples
    ///
    /// ```
    /// use whitaker_string_literals::facts::LiteralBody;
    ///
    /// assert_eq!(LiteralBody::new("beta").as_str(), "beta");
    /// ```
    #[must_use]
    pub const fn as_str(self) -> &'a str { self.0 }

    /// Returns the body length in bytes.
    ///
    /// # Examples
    ///
    /// ```
    /// use whitaker_string_literals::facts::LiteralBody;
    ///
    /// assert_eq!(LiteralBody::new("λ").len(), 2);
    /// ```
    #[must_use]
    pub const fn len(self) -> usize { self.0.len() }

    /// Returns whether the body is empty.
    ///
    /// # Examples
    ///
    /// ```
    /// use whitaker_string_literals::facts::LiteralBody;
    ///
    /// assert!(LiteralBody::new("").is_empty());
    /// ```
    #[must_use]
    pub const fn is_empty(self) -> bool { self.0.is_empty() }
}

/// A byte offset relative to the start of a [`LiteralBody`].
///
/// # Examples
///
/// ```
/// use whitaker_string_literals::facts::BodyOffset;
///
/// let offset = BodyOffset::from_index(3);
/// assert_eq!(offset.get(), 3);
/// ```
#[derive(Clone, Copy, Debug, Eq, Ord, PartialEq, PartialOrd)]
pub struct BodyOffset(usize);

impl BodyOffset {
    /// Creates an offset from a body-relative byte index.
    ///
    /// # Examples
    ///
    /// ```
    /// use whitaker_string_literals::facts::BodyOffset;
    ///
    /// assert_eq!(BodyOffset::from_index(5).get(), 5);
    /// ```
    #[must_use]
    pub const fn from_index(index: usize) -> Self { Self(index) }

    /// Returns the body-relative byte index.
    ///
    /// # Examples
    ///
    /// ```
    /// use whitaker_string_literals::facts::BodyOffset;
    ///
    /// assert_eq!(BodyOffset::from_index(2).get(), 2);
    /// ```
    #[must_use]
    pub const fn get(self) -> usize { self.0 }
}

/// The source facts supplied to the pure continuation policy.
///
/// Raw strings and non-string literal types have no cooked body to scan.
///
/// # Examples
///
/// ```
/// use whitaker_string_literals::facts::{LiteralBody, LiteralContext, LiteralFacts};
///
/// let facts = LiteralFacts::Cooked {
///     body: LiteralBody::new("alpha"),
///     context: LiteralContext::Expression,
/// };
/// assert!(matches!(facts, LiteralFacts::Cooked { .. }));
/// ```
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LiteralFacts<'a> {
    /// A cooked `str` literal with its grammatical context.
    Cooked {
        /// The source bytes between the literal's quotes.
        body: LiteralBody<'a>,
        /// The position in which the compiler found the literal.
        context: LiteralContext,
    },
    /// A byte string or C string, whose type cannot be preserved by `concat!`.
    NonStringLiteral,
    /// A raw string, raw byte string, or raw C string.
    Raw,
}

/// The grammatical position of a cooked literal.
///
/// # Examples
///
/// ```
/// use whitaker_string_literals::facts::{CaptureStatus, LiteralContext};
///
/// let context = LiteralContext::SourceFormatString {
///     capture: CaptureStatus::NoneObserved,
/// };
/// assert!(matches!(context, LiteralContext::SourceFormatString { .. }));
/// ```
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LiteralContext {
    /// A normal expression, where a `concat!` replacement is type-compatible.
    Expression,
    /// A source-authored format string and its implicit-capture status.
    SourceFormatString {
        /// Whether any format argument uses implicit capture.
        capture: CaptureStatus,
    },
    /// A literal whose source file is generated or outside the editable root.
    GeneratedSourceFile,
    /// A format string generated by another eager macro.
    GeneratedFormatString,
}

/// Whether a source-authored format string uses an implicit capture.
///
/// # Examples
///
/// ```
/// use whitaker_string_literals::facts::CaptureStatus;
///
/// assert_ne!(CaptureStatus::NoneObserved, CaptureStatus::Present);
/// ```
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum CaptureStatus {
    /// No captured format argument was observed.
    NoneObserved,
    /// At least one format argument uses an implicit capture.
    Present,
}
